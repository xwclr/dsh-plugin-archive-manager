/**
 * Assemble `lib/client.js` from the feature fragments under `src/features/`.
 *
 * A DSH package contributes exactly one `dsh.client` module, so the three
 * features this plugin carries are composed into a single browser bundle here
 * instead of shipping as three packages. The wrapper is deliberately thin: it
 * resolves the registration facade, evaluates each feature factory, unions the
 * services they require, and runs their `apply` functions one by one inside
 * separate try/catch blocks so a feature that meets an unexpected DOM cannot
 * take the others down with it.
 *
 * Run with `node scripts/build-client.mjs` (step two of `pnpm build`).
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (file) => readFileSync(join(root, file), 'utf8').trimEnd();

const skills = read('src/features/skills.factory.js');
const colors = read('src/features/colors.factory.js');
const archive = read('src/features/archive.factory.js');

const header = [
	'/**',
	' * Archive Manager — browser half (generated by scripts/build-client.mjs).',
	' *',
	' * One client module carries three features, because a package contributes',
	' * exactly one `dsh.client` entry:',
	' *',
	' * - 归档会话 / Archive Manager — a `settings.section` page that groups the',
	' *   archived sessions by project and restores or deletes them',
	' *   (`src/features/archive.factory.js`).',
	' * - 技能管理 / Skill Manager — the sidebar「技能」row and the page it opens',
	' *   (`src/features/skills.factory.js`).',
	' * - 工作区配色 / Workspace Colors — the workspace palette and row decoration',
	' *   (`src/features/colors.factory.js`).',
	' *',
	' * Edit the fragments under `src/features/`, never this file: `pnpm build`',
	' * regenerates it. Each fragment is a self-contained factory that returns',
	' * `{ apply, inject, ...exports }`, and `apply` runs them one by one inside',
	' * separate try/catch blocks so a feature that trips over shipped DOM cannot',
	' * take the other two down with it.',
	' */',
	'',
	'const __facade =',
	"\t(typeof _ModuleLoader__ !== 'undefined' ? _ModuleLoader__ : void 0) ||",
	"\t(typeof globalThis !== 'undefined' ? globalThis.__ModuleLoader__ : void 0);",
	'',
	'if (__facade === void 0 || typeof __facade.load !== \'function\') {',
	"\tthrow new Error('archive-manager: the module registration facade is missing');",
	'}',
	'',
	'__facade.load({',
	"\tid: 'dsh-plugin-archive-manager',",
	'\tfactory: (require) => {',
	'\t\tvar module = { exports: {} };',
	'\t\tvar exports = module.exports;',
	"\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: 'Module' });",
	''
].join('\n');

const sections = [];
sections.push(header);

/**
 * Push one feature factory into the bundle: the fragment is a self-contained
 * `(require) => { ... }` expression returning `{ apply, inject, ...exports }`.
 * @param name - local binding name.
 * @param fragment - the factory source.
 * @param comment - one-line description for the generated file.
 */
const embed = (name, fragment, comment) => {
	sections.push(`\t\t/** ${comment} */`);
	sections.push(`\t\tconst ${name} = (`);
	sections.push(fragment);
	sections.push('\t\t)(require);');
	sections.push('');
};

embed('__skills', skills, '技能管理 / Skill Manager (src/features/skills.factory.js).');
embed('__colors', colors, '工作区配色 / Workspace Colors (src/features/colors.factory.js).');
embed('__archive', archive, '归档会话 / Archive Manager (src/features/archive.factory.js).');

sections.push(`
		const __features = [
			{ key: 'archive', module: __archive },
			{ key: 'skills', module: __skills },
			{ key: 'colors', module: __colors }
		];

		/**
		 * The three switches the Host row declared (the Config schema in lib/index.js).
		 *
		 * The Host publishes them through an index injection before the page
		 * boots; a feature that is off registers nothing. A page without the
		 * global (an older Host, a cached index) keeps every feature on.
		 * @returns the resolved flags.
		 */
		function __readFeatureFlags() {
			const flags = { archive: true, skills: true, colors: true };
			try {
				const raw = typeof window !== 'undefined' ? window.__DSH_ARCHIVE_MANAGER_FEATURES__ : void 0;
				if (raw !== null && typeof raw === 'object') {
					for (const key of ['archive', 'skills', 'colors']) if (raw[key] === false) flags[key] = false;
				}
			} catch (error) {
				/* keep every feature on when the page global is unreadable */
			}
			return flags;
		}

		/** Services the three features need, de-duplicated. */
		const inject = Array.from(
			new Set(__features.flatMap((feature) => (Array.isArray(feature.module.inject) ? feature.module.inject : [])))
		);

		/**
		 * Browser plugin body: activate each bundled feature the row enabled,
		 * isolated so one failure cannot take the others down.
		 * @param ctx - client root context.
		 */
		function apply(ctx) {
			const flags = __readFeatureFlags();
			for (const feature of __features) {
				if (flags[feature.key] === false) {
					console.info('[archive-manager] feature disabled by config:', feature.key);
					continue;
				}
				try {
					feature.module.apply(ctx);
				} catch (error) {
					console.error('[archive-manager] a bundled feature failed to activate:', error);
				}
			}
		}

		exports.apply = apply;
		exports.inject = inject;
		exports.SkillManagerPage = __skills.SkillManagerPage;
		exports.SkillManagerIcon = __skills.SkillManagerIcon;
		exports.WorkspaceColorPalette = __colors.WorkspaceColorPalette;
		exports.ArchiveManagerPage = __archive.ArchiveManagerPage;
		exports.SessionDeleteMenuItem = __archive.SessionDeleteMenuItem;
		exports.DeleteSessionDialog = __archive.DeleteSessionDialog;
		return module.exports;
	}
});
`);

const output = sections.join('\n');
writeFileSync(join(root, 'lib/client.js'), output);
process.stdout.write(`wrote lib/client.js (${output.length} bytes)\n`);
